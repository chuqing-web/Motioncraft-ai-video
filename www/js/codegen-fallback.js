/**
 * Offline fallback: still emits HTML/CSS/JS *code strings* (as a model would),
 * not a fixed renderer. Composer executes this code to paint frames.
 */

export function synthesizeFilmCode(prompt, duration) {
  const text = prompt || '抽象短片';
  const n = Math.max(3, Math.min(5, Math.round(duration / 4)));
  const each = Math.max(2, Math.round((duration / n) * 10) / 10);
  const theme = /夜|neon|night|暗/i.test(text) ? 'night' : /白天|day|阳光/i.test(text) ? 'day' : 'night';
  const beats = splitBeats(text, n);
  const scenes = [];

  for (let i = 0; i < n; i++) {
    const title = `镜头 ${i + 1}`;
    const caption = beats[i];
    const html = `<div class="layer"><div class="caption"></div></div>`;
    const css = sceneCss(theme, i);
    const js = sceneJs({ theme, caption, index: i, hasWalker: /人|剪影|walk|character/i.test(text) || i === 1 });
    scenes.push({
      title,
      duration: each,
      text: caption,
      html,
      css,
      js,
      character: false,
      effect: 'none',
      chart: false,
      camera: 'static',
    });
  }

  return {
    name: text.slice(0, 24) || 'AI 短片',
    duration,
    scenes,
    _source: 'codegen-fallback',
  };
}

function sceneCss(theme, index) {
  const sky =
    theme === 'day'
      ? 'linear-gradient(180deg,#7ec8e3,#f7e7c6)'
      : 'linear-gradient(180deg,#05070f,#1d1630)';
  return `
.layer { position:absolute; inset:0; overflow:hidden; background:${sky}; }
.caption {
  position:absolute; left:50%; bottom:12%; transform:translateX(-50%);
  padding:10px 18px; background:rgba(0,0,0,.45); color:#e7ecf3;
  font:600 28px/1.2 "Segoe UI","Microsoft YaHei",sans-serif;
  border-radius:10px; white-space:nowrap; opacity:0;
}
`.trim();
}

function sceneJs({ theme, caption, index, hasWalker }) {
  // Returns a factory string the Composer will eval — draws every frame.
  return `
(function(){
  const CAPTION = ${JSON.stringify(caption)};
  const THEME = ${JSON.stringify(theme)};
  const IDX = ${index};
  const WALKER = ${hasWalker ? 'true' : 'false'};
  let captionEl;
  return {
    setup({ root, canvas, ctx }) {
      captionEl = root.querySelector('.caption');
      if (captionEl) captionEl.textContent = CAPTION;
    },
    draw({ ctx, canvas, t, duration, root }) {
      const w = canvas.width, h = canvas.height;
      const g = ctx.createLinearGradient(0,0,0,h);
      if (THEME === 'day') { g.addColorStop(0,'#7ec8e3'); g.addColorStop(1,'#f7e7c6'); }
      else { g.addColorStop(0,'#05070f'); g.addColorStop(1,'#1d1630'); }
      ctx.fillStyle = g; ctx.fillRect(0,0,w,h);

      // city blocks generated by code (not a host template engine)
      ctx.fillStyle = '#121722';
      ctx.beginPath(); ctx.moveTo(0, h*0.58);
      for (let i=0;i<10;i++){
        const x = (i+1)/11*w;
        const y = h*(0.28 + 0.2*Math.abs(Math.sin(i*1.7+IDX)));
        ctx.lineTo(x,y);
      }
      ctx.lineTo(w,h*0.45); ctx.lineTo(w,h); ctx.lineTo(0,h); ctx.closePath(); ctx.fill();

      for (let i=0;i<30;i++){
        ctx.globalAlpha = 0.4 + 0.6*(0.5+0.5*Math.sin(t*4+i));
        ctx.fillStyle = i%2? '#3dd6c6':'#f0a35e';
        ctx.fillRect((i*47+IDX*13)%w, h*0.55+(i%6)*16, 3, 3);
      }
      ctx.globalAlpha = 1;

      if (WALKER) {
        const x = -60 + (w+120) * Math.min(1, t/Math.max(0.01,duration));
        ctx.fillStyle = '#05070b';
        ctx.beginPath(); ctx.arc(x+18, h*0.62, 14, 0, Math.PI*2); ctx.fill();
        ctx.fillRect(x+4, h*0.62, 28, 86);
      }

      // Caption only on canvas (no attached text node) to avoid double subtitles
      if (captionEl) captionEl.style.opacity = '0';
      const fade = Math.min(1, t/0.4) * Math.min(1, (duration - t) / 0.35);
      if (fade > 0 && CAPTION) {
        ctx.save();
        ctx.globalAlpha = fade;
        ctx.fillStyle = 'rgba(0,0,0,0.5)';
        ctx.font = 'bold 28px Segoe UI, Microsoft YaHei, sans-serif';
        const tw = ctx.measureText(CAPTION).width;
        const tx = (w-tw)/2, ty = h*0.86;
        ctx.fillRect(tx-14, ty-30, tw+28, 42);
        ctx.fillStyle = '#e7ecf3';
        ctx.fillText(CAPTION, tx, ty);
        ctx.restore();
      }

      ctx.fillStyle = '#3dd6c6';
      ctx.fillRect(0, h-4, w*(t/Math.max(0.01,duration)), 4);
    }
  };
})()
`.trim();
}

function splitBeats(text, n) {
  const parts = text.split(/[，,。.!！？?\s]+/).filter(Boolean);
  const out = [];
  for (let i = 0; i < n; i++) out.push(parts[i % Math.max(parts.length, 1)] || `段落 ${i + 1}`);
  return out;
}
